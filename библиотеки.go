func библиотеки() {
	формат.ВывестиСтроку("--- библиотеки ---")

	// строки
	фраза := "  Мама мыла раму  "
	слова := строки.Поля(строки.ВНижний(фраза))
	формат.ВывестиФ("слова=%q содержит «раму»=%v\n", слова, строки.Содержит(фраза, "раму"))

	var с строки.Строитель
	с.Записать("Привет").ЗаписатьРуну(',').Записать(" ").Записать("строитель")
	формат.ЗаписатьСтроку(ос.Вывод, с.Строка())

	// срезы и карты
	оценки := Карта[строка, цел]{"Вася": 4, "Петя": 5, "Маша": 3}
	имена := срезы.Отсортированный(карты.Ключи(оценки))
	формат.ВывестиСтроку("имена:", имена, "лучшая оценка:", срезы.Макс(срезы.Собрать(карты.Значения(оценки))))

	// преобр и ошибки
	if _, ош := преобр.ИзСтроки("сорок два"); ош != nil {
		if ошЧисла, ок := ошибки.КакТип[*преобр.ОшибкаЧисла](ош); ок {
			формат.ВывестиСтроку("не число:", ошЧисла.Num, "синтаксис?", ошибки.Является(ош, преобр.ОшибкаСинтаксиса))
		}
	}

	// матем
	формат.ВывестиФ("√2=%.4f  sin(π/2)=%v\n", матем.Корень(2), матем.Синус(матем.Пи/2))

	// синхр и время
	var (
		группа  синхр.ГруппаОжидания
		мьютекс синхр.Мьютекс
		счётчик цел
	)
	начало := время.Сейчас()
	for range 10 {
		группа.Запустить(func() {
			время.Спать(10 * время.Миллисекунда)
			мьютекс.Захватить()
			defer мьютекс.Освободить()
			счётчик++
		})
	}
	группа.Ждать()
	формат.ВывестиФ("счётчик=%d за %v, пятница? %v\n", счётчик, время.ПрошлоС(начало).Round(время.Миллисекунда), время.Сейчас().Weekday() == время.Пятница)
}
