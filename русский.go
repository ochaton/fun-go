// создать — аналог make: создать[Срез[цел]](длина, ёмкость?),
// создать[Карта[K, V]](подсказка?), создать[Канал[T]](буфер?).
// make нельзя вызвать на объединении срез|карта|канал (нет core type),
// поэтому через reflect; ошибки ловятся в рантайме, а не компилятором.
func создать[T любой](размеры ...цел) T {
	тип := отражение.ТипДля[T]()
	арг := func(и цел) цел {
		if и < len(размеры) {
			return размеры[и]
		}
		return 0
	}
	switch тип.Kind() {
	case отражение.Срез:
		if len(размеры) == 0 || len(размеры) > 2 {
			паника(строкаф("создать[%v]: нужна длина и, опционально, ёмкость", тип))
		}
		ёмк := арг(0)
		if len(размеры) == 2 {
			ёмк = размеры[1]
		}
		return отражение.СоздатьСрез(тип, размеры[0], ёмк).Interface().(T)
	case отражение.Карта:
		if len(размеры) > 1 {
			паника(строкаф("создать[%v]: лишние аргументы", тип))
		}
		return отражение.СоздатьКарту(тип, арг(0)).Interface().(T)
	case отражение.Канал:
		if len(размеры) > 1 {
			паника(строкаф("создать[%v]: лишние аргументы", тип))
		}
		return отражение.СоздатьКанал(тип, арг(0)).Interface().(T)
	}
	паника(строкаф("создать[%v]: можно только срез, карту или канал", тип))
	panic("недостижимо")
}
