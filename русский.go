func мин[T упорядочимый](x T, ещё ...T) T {
	for _, y := range ещё {
		x = min(x, y)
	}
	return x
}
func макс[T упорядочимый](x T, ещё ...T) T {
	for _, y := range ещё {
		x = max(x, y)
	}
	return x
}

